# Builds the ESP32 firmware with arduino-cli and the Arduino-ESP32 core (3.x).
# The Arduino sketch is assembled in firmware\build\esp32\IntegrAlo from the portable core
# (src\core) and the ESP32 layer (src\esp32), so both builds always use the same core files.
#   .\firmware\scripts\build-esp32.ps1                    compile only
#   .\firmware\scripts\build-esp32.ps1 -Port COM5         compile and write it to the board
# The assembled folder can also be opened in the Arduino IDE (add ArduinoJson 7.4.3 there).
param(
  [string]$Port,
  [string]$Fqbn = 'esp32:esp32:esp32'  # "ESP32 Dev Module"
)
$ErrorActionPreference = 'Stop'

$fw = Split-Path -Parent $PSScriptRoot
$repo = Split-Path -Parent $fw
$cli = Join-Path $repo '.tools\arduino-cli\arduino-cli.exe'
if (-not (Test-Path $cli)) {
  $found = Get-Command arduino-cli -ErrorAction SilentlyContinue
  if (-not $found) { throw "arduino-cli not found in $cli or in PATH" }
  $cli = $found.Source
}

$out = Join-Path $fw 'build\esp32'
$sketch = Join-Path $out 'IntegrAlo'
if (Test-Path $sketch) { Remove-Item -Recurse -Force $sketch }
New-Item -ItemType Directory -Force "$sketch\src\core", "$sketch\src\esp32" | Out-Null
Copy-Item "$fw\src\core\*" "$sketch\src\core"
Copy-Item "$fw\src\esp32\*" "$sketch\src\esp32"
# Arduino needs a .ino named like its folder; setup() and loop() are in src\esp32\esp32_main.cpp.
Set-Content -Encoding utf8 "$sketch\IntegrAlo.ino" @'
// IntegrAlo node firmware. Generated by firmware/scripts/build-esp32.ps1: do not edit here.
// The code is in src/core (portable, shared with the PC build) and src/esp32 (this board).
'@

$common = @('--fqbn', $Fqbn)
& $cli compile @common --library "$fw\lib\ArduinoJson" --warnings default --output-dir "$out\bin" $sketch
if ($LASTEXITCODE -ne 0) { throw 'ESP32 build failed' }

if ($Port) {
  & $cli upload @common -p $Port --input-dir "$out\bin" $sketch
  if ($LASTEXITCODE -ne 0) { throw "upload to $Port failed" }
}
Write-Host "done: $out\bin"
