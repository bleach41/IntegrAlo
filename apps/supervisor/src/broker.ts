import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { Settings, writeAtomically } from './settings';

/**
 * Mosquitto configuration generated from the settings (RNF-05, RNF-06):
 * - listens on every network interface, so nodes on the Wi-Fi can connect;
 * - no anonymous access: one account for the core and one shared by the nodes;
 * - ACL: the core may use every platform topic; nodes only the nodes' topics.
 * Paths use forward slashes, which Mosquitto accepts on Windows.
 */
export function mosquittoConfig(settings: Settings, brokerDir: string): string {
  const path = (p: string) => p.replace(/\\/g, '/');
  return [
    '# Generated by the IntegrAlo supervisor. Changes are overwritten on start.',
    'per_listener_settings false',
    'allow_anonymous false',
    `password_file ${path(join(brokerDir, 'passwords'))}`,
    `acl_file ${path(join(brokerDir, 'acl'))}`,
    `listener ${settings.brokerPort}`,
    'persistence true',
    `persistence_location ${path(join(brokerDir, 'data'))}/`,
    'autosave_interval 60',
    'log_dest stdout',
    'log_type error',
    'log_type warning',
    'log_type notice',
    '',
  ].join('\n');
}

export function aclFile(settings: Settings): string {
  const prefix = settings.topicPrefix;
  return [
    `user ${settings.core.username}`,
    `topic readwrite ${prefix}/#`,
    '',
    `user ${settings.nodes.username}`,
    `topic readwrite ${prefix}/nodes/#`,
    '',
  ].join('\n');
}

/**
 * Writes configuration, ACL and the password file. Passwords are hashed by Mosquitto's
 * own tool (mosquitto_passwd), so the broker never stores them in clear text.
 */
export function prepareBroker(settings: Settings, brokerDir: string, mosquittoDir: string): string {
  mkdirSync(join(brokerDir, 'data'), { recursive: true });
  const configFile = join(brokerDir, 'mosquitto.conf');
  writeAtomically(configFile, mosquittoConfig(settings, brokerDir));
  writeAtomically(join(brokerDir, 'acl'), aclFile(settings));

  const passwords = join(brokerDir, 'passwords');
  rmSync(passwords, { force: true });
  const tool = join(mosquittoDir, 'mosquitto_passwd.exe');
  const passwd = existsSync(tool) ? tool : 'mosquitto_passwd';
  execFileSync(passwd, ['-c', '-b', passwords, settings.core.username, settings.core.password], { stdio: 'ignore' });
  execFileSync(passwd, ['-b', passwords, settings.nodes.username, settings.nodes.password], { stdio: 'ignore' });
  return configFile;
}

/**
 * Mosquitto folder: INTEGRALO_MOSQUITTO_DIR if set; else the copy bundled with an installed
 * IntegrAlo (<root>/mosquitto); else, during development, the default Windows install.
 */
export function findMosquittoDir(root: string, env: NodeJS.ProcessEnv = process.env): string {
  if (env.INTEGRALO_MOSQUITTO_DIR) return env.INTEGRALO_MOSQUITTO_DIR;
  const bundled = join(root, 'mosquitto');
  return existsSync(join(bundled, 'mosquitto.exe')) ? bundled : 'C:/Program Files/mosquitto';
}
